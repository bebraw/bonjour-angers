import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.resolve(fileURLToPath(new URL('..',import.meta.url)));
const readJSON=async name=>JSON.parse(await fs.readFile(path.join(root,'data',name),'utf8'));
const sandbox={window:{}};
vm.runInNewContext(await fs.readFile(path.join(root,'dist/vocabulary-data.js'),'utf8'),sandbox);
const words=sandbox.window.VOCABULARY_WORDS,ids=new Set(words.map(w=>w.id));
const everyday=await readJSON('finnish-everyday.json'),professional=await readJSON('finnish-food-academic.json');
const visuals=await readJSON('visual-anchors.json'),sounds=await readJSON('sound-contrasts.json');
for(const id of Object.keys(everyday))if(Object.hasOwn(professional,id))throw Error('Duplicate Finnish entry: '+id);
const support={...everyday,...professional};
if(Object.keys(support).length!==words.length)throw Error('Finnish support must cover all built-in words');
for(const [id,s] of Object.entries(support)){
  if(!ids.has(id))throw Error('Unknown Finnish word ID: '+id);
  for(const key of ['fi','soundFi'])if(typeof s[key]!=='string'||!s[key].trim())throw Error('Missing '+key+' for '+id);
  if(!Array.isArray(s.fiAccepted)||s.fiAccepted.some(x=>typeof x!=='string'||!x.trim()))throw Error('Invalid Finnish synonyms: '+id);
  if(!s.anchor||!['cognate','pattern','scene'].includes(s.anchor.type)||typeof s.anchor.text!=='string'||!s.anchor.text.trim())throw Error('Missing memory anchor: '+id);
  if(s.article){
    const a=s.article,word=words.find(w=>w.id===id);
    if(!['m','f'].includes(a.gender)||!['le','la','les'].includes(a.definite)||!['un','une','des'].includes(a.indefinite)||typeof a.base!=='string'||!a.base||typeof a.note!=='string'||!a.note)throw Error('Invalid article: '+id);
    if((word.fr.startsWith('la ')&&a.gender!=='f')||(word.fr.startsWith('le ')&&a.gender!=='m'))throw Error('Article contradicts dictionary form: '+id);
    if(a.definite!=='les'&&(a.definite!==(a.gender==='m'?'le':'la')||a.indefinite!==(a.gender==='m'?'un':'une')))throw Error('Article forms disagree: '+id);
    if(a.acceptedGenders?.length>1&&a.quiz!==false)throw Error('Variable gender must not be graded as binary: '+id);
  }
}
const sprite=await fs.readFile(path.join(root,'dist/images/word-anchors.svg'),'utf8');
for(const [id,visual] of Object.entries(visuals)){
  if(!ids.has(id)||typeof visual.key!=='string'||!/^[a-z0-9-]+$/.test(visual.key)||!sprite.includes('id="'+visual.key+'"')||!visual.label)throw Error('Invalid picture anchor: '+id);
  support[id].visual=visual;
}
for(const [id,sound] of Object.entries(sounds)){
  if(!ids.has(id)||!Array.isArray(sound.choices)||sound.choices.length!==2||new Set(sound.choices).size!==2||!sound.choices.includes(sound.target)||!sound.note||!sound.targetFi||!sound.foilFi)throw Error('Invalid sound contrast: '+id);
  support[id].sound=sound;
}
const output='/* Original Finnish glosses, memory anchors and teaching notes. Generated by scripts/build-learning-data.mjs. */\n(()=>{\nconst support='+JSON.stringify(support,null,2)+';\nfor(const word of window.VOCABULARY_WORDS)Object.assign(word,support[word.id]||{});\n})();\n';
await fs.writeFile(path.join(root,'dist/learning-data.js'),output);
console.log('Prepared '+words.length+' Finnish word guides, '+Object.keys(visuals).length+' picture anchors and '+Object.keys(sounds).length+' sound contrasts');
